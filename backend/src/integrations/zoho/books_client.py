"""
Zoho Books API Client
Manages Delivery Challans and Tax Invoices with strict financial idempotency.

Prime Invariant #5:
Every transaction pushed to Zoho Books, Inventory, or CRM must pass an explicit Idempotency-Key.
Duplicate delivery submissions must never produce duplicate tax invoices or challans.
"""

from typing import Any, Dict, List, Optional
import httpx
from backend.src.config import settings
from backend.src.integrations.zoho.oauth import ZohoOAuthManager, zoho_auth_manager


class ZohoBooksClient:
    """Client for Zoho Books accounting integration."""

    def __init__(
        self,
        base_url: Optional[str] = None,
        org_id: Optional[str] = None,
        auth_manager: Optional[ZohoOAuthManager] = None,
    ):
        self.base_url = base_url or settings.ZOHO_BASE_URL
        self.org_id = org_id or settings.ZOHO_BOOKS_ORG_ID
        self.auth = auth_manager or zoho_auth_manager

    def _get_headers(self, idempotency_key: str) -> Dict[str, str]:
        token = self.auth.get_access_token()
        return {
            "Authorization": f"Zoho-oauthtoken {token}",
            "Idempotency-Key": idempotency_key,
            "Content-Type": "application/json;charset=UTF-8",
        }

    def create_delivery_challan(
        self,
        customer_id: str,
        challan_number: str,
        idempotency_key: str,
        line_items: List[Dict[str, Any]],
        notes: Optional[str] = None,
    ) -> Dict[str, Any]:
        """
        Creates a Delivery Challan in Zoho Books under GST Rule 55.
        Requires explicit Idempotency-Key.
        """
        if not idempotency_key:
            raise ValueError("Idempotency-Key is mandatory for Zoho Books transactions (Prime Rule #5)")

        url = f"{self.base_url}/api/v3/deliverychallans?organization_id={self.org_id}"
        payload = {
            "customer_id": customer_id,
            "delivery_challan_number": challan_number,
            "line_items": line_items,
            "notes": notes or f"Generated by CTMS - Challan {challan_number}",
        }

        with httpx.Client(timeout=15.0) as client:
            resp = client.post(
                url,
                json=payload,
                headers=self._get_headers(idempotency_key),
            )
            resp.raise_for_status()
            return resp.json()

    def create_sales_invoice(
        self,
        customer_id: str,
        invoice_number: str,
        idempotency_key: str,
        line_items: List[Dict[str, Any]],
        notes: Optional[str] = None,
    ) -> Dict[str, Any]:
        """
        Creates a Tax Invoice in Zoho Books for gas sales or monthly rental.
        Requires explicit Idempotency-Key.
        """
        if not idempotency_key:
            raise ValueError("Idempotency-Key is mandatory for Zoho Books transactions (Prime Rule #5)")

        url = f"{self.base_url}/api/v3/invoices?organization_id={self.org_id}"
        payload = {
            "customer_id": customer_id,
            "invoice_number": invoice_number,
            "line_items": line_items,
            "notes": notes or f"Generated by CTMS - Invoice {invoice_number}",
        }

        with httpx.Client(timeout=15.0) as client:
            resp = client.post(
                url,
                json=payload,
                headers=self._get_headers(idempotency_key),
            )
            resp.raise_for_status()
            return resp.json()
